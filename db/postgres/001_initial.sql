-- Supabase PostgreSQL. La API pública de Supabase no expone el esquema app.
CREATE SCHEMA IF NOT EXISTS app;
SET search_path TO app, public;

CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE CHECK (char_length(email) BETWEEN 3 AND 254 AND email = lower(email)),
  display_name text NOT NULL CHECK (char_length(display_name) BETWEEN 2 AND 80),
  password_hash text NOT NULL CHECK (char_length(password_hash) > 0),
  created_at bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  id uuid PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  created_at bigint NOT NULL,
  expires_at bigint NOT NULL,
  revoked_at bigint,
  revoke_reason text CHECK (revoke_reason IN ('LOGOUT', 'PASSWORD_RESET')),
  CHECK (expires_at > created_at),
  CHECK ((revoked_at IS NULL) = (revoke_reason IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  created_at bigint NOT NULL,
  expires_at bigint NOT NULL,
  used_at bigint,
  CHECK (expires_at > created_at)
);

CREATE TABLE IF NOT EXISTS mail_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_email text NOT NULL CHECK (char_length(to_email) BETWEEN 3 AND 254),
  subject text NOT NULL CHECK (char_length(subject) > 0),
  body text NOT NULL CHECK (char_length(body) > 0),
  created_at bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS offers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  title text NOT NULL CHECK (char_length(title) BETWEEN 5 AND 120),
  description text NOT NULL CHECK (char_length(description) BETWEEN 20 AND 2000),
  province text NOT NULL CHECK (province IN (
    'AZUAY','BOLIVAR','CANAR','CARCHI','CHIMBORAZO','COTOPAXI',
    'EL_ORO','ESMERALDAS','GALAPAGOS','GUAYAS','IMBABURA','LOJA',
    'LOS_RIOS','MANABI','MORONA_SANTIAGO','NAPO','ORELLANA','PASTAZA',
    'PICHINCHA','SANTA_ELENA','SANTO_DOMINGO_DE_LOS_TSACHILAS',
    'SUCUMBIOS','TUNGURAHUA','ZAMORA_CHINCHIPE'
  )),
  location_text text NOT NULL CHECK (char_length(location_text) BETWEEN 5 AND 200),
  starts_at bigint NOT NULL,
  capacity integer NOT NULL CHECK (capacity BETWEEN 1 AND 1000),
  is_published boolean NOT NULL DEFAULT false,
  created_at bigint NOT NULL,
  updated_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_offers_owner_province_starts ON offers (owner_id, province, starts_at, id);
CREATE INDEX IF NOT EXISTS idx_offers_owner_starts ON offers (owner_id, starts_at, id);
CREATE INDEX IF NOT EXISTS idx_offers_public_starts ON offers (is_published, starts_at, id);

-- Solo metadatos; los bytes de la imagen viven en Storage/site-imgs.
CREATE TABLE IF NOT EXISTS offer_photos (
  offer_id bigint PRIMARY KEY REFERENCES offers(id) ON DELETE CASCADE,
  storage_path text NOT NULL UNIQUE,
  content_type text NOT NULL CHECK (content_type IN ('image/jpeg','image/png','image/webp')),
  alt_text text NOT NULL CHECK (char_length(alt_text) BETWEEN 1 AND 160),
  size_bytes bigint NOT NULL CHECK (size_bytes BETWEEN 1 AND 50000000)
);

CREATE TABLE IF NOT EXISTS chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room text NOT NULL DEFAULT 'general' CHECK (room = 'general'),
  author_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  author_name text NOT NULL CHECK (char_length(author_name) BETWEEN 2 AND 80),
  text text NOT NULL CHECK (char_length(text) BETWEEN 1 AND 500),
  client_message_id text NOT NULL CHECK (char_length(client_message_id) BETWEEN 1 AND 64),
  created_at bigint NOT NULL,
  UNIQUE (author_id, client_message_id)
);
CREATE INDEX IF NOT EXISTS idx_chat_room_id ON chat_messages (room, id);
